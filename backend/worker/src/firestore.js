// Firestore REST: value encoding and the translation of small "ops" into commit writes.
// Pure functions, no network (tested in test/firestore.test.js).

export function encodeValue(v) {
  if (v === null || v === undefined) return { nullValue: null };
  if (v instanceof Date) return { timestampValue: v.toISOString() };
  if (typeof v === 'string') return { stringValue: v };
  if (typeof v === 'boolean') return { booleanValue: v };
  if (typeof v === 'number') {
    return Number.isInteger(v) ? { integerValue: String(v) } : { doubleValue: v };
  }
  if (Array.isArray(v)) return { arrayValue: { values: v.map(encodeValue) } };
  return { mapValue: { fields: encodeFields(v) } };
}

export function encodeFields(obj) {
  return Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, encodeValue(v)]));
}

export function decodeValue(v) {
  if ('stringValue' in v) return v.stringValue;
  if ('booleanValue' in v) return v.booleanValue;
  if ('integerValue' in v) return Number(v.integerValue);
  if ('doubleValue' in v) return v.doubleValue;
  if ('timestampValue' in v) return new Date(v.timestampValue);
  if ('arrayValue' in v) return (v.arrayValue.values ?? []).map(decodeValue);
  if ('mapValue' in v) return decodeFields(v.mapValue.fields ?? {});
  return null;
}

export function decodeFields(fields) {
  return Object.fromEntries(Object.entries(fields ?? {}).map(([k, v]) => [k, decodeValue(v)]));
}

/// A document as the rest of the Worker sees it: `path` is relative to `.../documents/`.
export function decodeDoc(raw) {
  const path = raw.name.split('/documents/')[1];
  return {
    path,
    id: path.split('/').pop(),
    updateTime: raw.updateTime,
    fields: decodeFields(raw.fields),
  };
}

/// `fields` of a `map` field may use ids as keys; the path of a key with odd characters is
/// quoted. Product ids are generated by the app and safe, but quote anyway.
const fieldPath = (p) => (/^[A-Za-z_][A-Za-z0-9_]*$/.test(p) ? p : `\`${p.replace(/`/g, '\\`')}\``);

/// One op:
///   { path, set?: {field: value}, remove?: [field], increment?: {field: n},
///     serverTime?: [field], must?: {updateTime} | {exists: bool} }
/// `set` and `remove` are the masked fields (everything else in the document stays).
export function opToWrite(op, documentsBase) {
  const write = {};
  const set = op.set ?? {};
  const mask = [...Object.keys(set), ...(op.remove ?? [])].map(fieldPath);
  write.update = { name: `${documentsBase}/${op.path}`, fields: encodeFields(set) };
  write.updateMask = { fieldPaths: mask };
  const transforms = [
    ...Object.entries(op.increment ?? {}).map(([f, n]) => ({
      fieldPath: fieldPath(f),
      increment: { integerValue: String(n) },
    })),
    ...(op.serverTime ?? []).map((f) => ({
      fieldPath: fieldPath(f),
      setToServerValue: 'REQUEST_TIME',
    })),
  ];
  if (transforms.length) write.updateTransforms = transforms;
  if (op.must?.updateTime) write.currentDocument = { updateTime: op.must.updateTime };
  else if (op.must && 'exists' in op.must) write.currentDocument = { exists: op.must.exists };
  return write;
}
